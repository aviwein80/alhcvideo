// Regenerates src/brand/logoPaths.ts from assets/brand/logo.svg.
// Run after replacing the logo file:  node scripts/extract-logo-paths.mjs
// The official SVG groups its artwork by fill colour: the orange tree mark
// first, then the maroon "AUTUMN LAKE" / "HEALTHCARE" lettering.
import {readFileSync, writeFileSync} from 'node:fs';
import {getSubpaths, getBoundingBox} from '@remotion/paths';

const svg = readFileSync(new URL('../assets/brand/logo.svg', import.meta.url), 'utf8');

const viewBox = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
const fills = Object.fromEntries(
	[...svg.matchAll(/\.(st\d+)\{fill:(#[0-9A-Fa-f]{3,6});\}/g)].map((m) => [m[1], m[2]]),
);

const shapes = [];
for (const m of svg.matchAll(/<path class="(st\d+)" d="([^"]+)"/g)) {
	const fill = fills[m[1]];
	const d = m[2].replace(/\s+/g, ' ').trim();
	let prev = null;
	for (const sub of getSubpaths(d)) {
		const b = getBoundingBox(sub);
		// A sub-path that sits wholly inside the previous one is a counter (the
		// hole in an "A" or "R"), so it stays part of that shape.
		if (prev && b.x1 >= prev.b.x1 && b.x2 <= prev.b.x2 && b.y1 >= prev.b.y1 && b.y2 <= prev.b.y2) {
			prev.shape.d += ' ' + sub;
			continue;
		}
		const shape = {
			d: sub,
			fill,
			cx: +((b.x1 + b.x2) / 2).toFixed(1),
			cy: +((b.y1 + b.y2) / 2).toFixed(1),
			w: +(b.x2 - b.x1).toFixed(1),
			h: +(b.y2 - b.y1).toFixed(1),
		};
		shapes.push(shape);
		prev = {shape, b};
	}
}

if (process.argv.includes('--print')) {
	shapes.forEach((s, i) => console.log(i, s.fill, s.cx, s.cy, s.w, s.h, s.d.length));
	process.exit(0);
}

const out = `// GENERATED by scripts/extract-logo-paths.mjs from assets/brand/logo.svg — do not edit by hand.
// Each entry is one closed shape of the official logo, with its bounding-box
// centre so shapes can be animated individually without redrawing anything.
export type LogoShape = {d: string; fill: string; cx: number; cy: number; w: number; h: number};

export const LOGO_VIEWBOX = {x: ${viewBox[0]}, y: ${viewBox[1]}, width: ${viewBox[2]}, height: ${viewBox[3]}};

export const LOGO_SHAPES: LogoShape[] = ${JSON.stringify(shapes, null, '\t')};
`;
writeFileSync(new URL('../src/brand/logoPaths.ts', import.meta.url), out);
console.log(`Wrote ${shapes.length} shapes`);
